-- Helper functions allow staff-only policies without recursive profile lookups.
create or replace function public.is_scholarship_staff()
returns boolean language sql stable security definer set search_path = public
as $$ select exists (select 1 from public.profiles where id = auth.uid() and role = 'staff'); $$;
revoke all on function public.is_scholarship_staff() from public;
grant execute on function public.is_scholarship_staff() to authenticated;

create or replace function public.is_scholarship_scholar()
returns boolean language sql stable security definer set search_path = public
as $$ select exists (select 1 from public.profiles where id = auth.uid() and role = 'scholar'); $$;
revoke all on function public.is_scholarship_scholar() from public;
grant execute on function public.is_scholarship_scholar() to authenticated;

-- Automatically creates a scholar profile for new self-registrations.
-- Public registration can only create a scholar, never a staff profile.
create or replace function public.create_scholar_profile()
returns trigger language plpgsql security definer set search_path = public
as $$
declare p_id bigint;
begin
  if coalesce(new.raw_user_meta_data->>'role','scholar') <> 'scholar' then
    raise exception 'Only scholar self-registration is allowed';
  end if;
  begin p_id := nullif(new.raw_user_meta_data->>'program_id','')::bigint; exception when others then p_id := null; end;
  insert into public.profiles(id, student_id, full_name, email, role, program_id)
  values(new.id, nullif(new.raw_user_meta_data->>'student_id',''), coalesce(nullif(new.raw_user_meta_data->>'full_name',''), 'Scholar'), new.email, 'scholar', p_id)
  on conflict(id) do nothing;
  return new;
end; $$;
drop trigger if exists on_auth_user_created_scholar_profile on auth.users;
create trigger on_auth_user_created_scholar_profile after insert on auth.users
for each row execute procedure public.create_scholar_profile();

alter table public.programs enable row level security;
alter table public.profiles enable row level security;
alter table public.submissions enable row level security;
alter table public.audit_log enable row level security;

drop policy if exists programs_read_public on public.programs;
create policy programs_read_public on public.programs for select to anon, authenticated using (true);

drop policy if exists profiles_read_self_or_staff on public.profiles;
create policy profiles_read_self_or_staff on public.profiles for select to authenticated using (id = auth.uid() or public.is_scholarship_staff());
-- Users cannot update their own role or profile via the browser. Staff profile changes are done by project admin in SQL editor.

drop policy if exists submissions_read_owner_or_staff on public.submissions;
create policy submissions_read_owner_or_staff on public.submissions for select to authenticated using (scholar_id = auth.uid() or public.is_scholarship_staff());
drop policy if exists submissions_insert_owner_scholar on public.submissions;
create policy submissions_insert_owner_scholar on public.submissions for insert to authenticated with check (
  scholar_id = auth.uid() and public.is_scholarship_scholar()
);
drop policy if exists submissions_update_staff_only on public.submissions;
create policy submissions_update_staff_only on public.submissions for update to authenticated using (public.is_scholarship_staff()) with check (public.is_scholarship_staff());

drop policy if exists audit_read_staff_or_owner on public.audit_log;
create policy audit_read_staff_or_owner on public.audit_log for select to authenticated using (
  public.is_scholarship_staff() or exists (select 1 from public.submissions s where s.id = submission_id and s.scholar_id = auth.uid())
);
drop policy if exists audit_insert_staff_actor on public.audit_log;
create policy audit_insert_staff_actor on public.audit_log for insert to authenticated with check (actor_id = auth.uid() and public.is_scholarship_staff());

grant select on public.programs to anon, authenticated;
grant select on public.profiles to authenticated;
grant select, insert on public.submissions to authenticated;
grant update on public.submissions to authenticated;
grant select, insert on public.audit_log to authenticated;
